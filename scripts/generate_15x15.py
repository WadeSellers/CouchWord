# Verify symmetry
def verify_template(template):
    rows = len(template)
    cols = len(template[0])
    errors = []
    for r in range(rows):
        for c in range(cols):
            sr, sc = rows - 1 - r, cols - 1 - c
            if template[r][c] != template[sr][sc]:
                errors.append(f"({r},{c})={template[r][c]} vs ({sr},{sc})={template[sr][sc]}")
    return errors

