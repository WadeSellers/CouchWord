def get_template_slots(grid):
    """Extract all across and down slots from the grid template."""
    rows = len(grid)
    cols = len(grid[0])
    slots = []

    # Across slots
    for r in range(rows):
        c = 0
        while c < cols:
            if grid[r][c] != '#':
                start = c
                while c < cols and grid[r][c] != '#':
                    c += 1
                length = c - start
                if length >= 3:
                    cells = [(r, start + i) for i in range(length)]
                    slots.append(('across', cells, length))
            else:
                c += 1

    # Down slots
    for c in range(cols):
        r = 0
        while r < rows:
            if grid[r][c] != '#':
                start = r
                while r < rows and grid[r][c] != '#':
                    r += 1
                length = r - start
                if length >= 3:
                    cells = [(start + i, c) for i in range(length)]
                    slots.append(('down', cells, length))
            else:
                r += 1

    return slots


def matches_pattern(word, pattern):
    """Check if a word matches a constraint pattern."""
    for w, p in zip(word, pattern):
        if p != '.' and p != w:
            return False
    return True


def get_candidates(word_dict, length, pattern, used_words):
    """Get candidate words for a slot given constraints."""
    if length not in word_dict:
        return []
    return [(w, c) for w, c in word_dict[length]
            if w not in used_words and matches_pattern(w, pattern)]


def count_candidates(word_dict, length, pattern, used_words):
    """Count matching candidates."""
    if length not in word_dict:
        return 0
    return sum(1 for w, _ in word_dict[length]
               if w not in used_words and matches_pattern(w, pattern))


def solve(grid, slots, word_dict, slot_order, idx, used_words, start_time,
          time_limit=300, best_progress=[0]):
    """Backtracking solver with constraint propagation."""
    if time.time() - start_time > time_limit:
        return False

    if idx >= len(slot_order):
        return True

    if idx > best_progress[0]:
        best_progress[0] = idx
        elapsed = time.time() - start_time
        d, cells, l = slots[slot_order[idx-1]]
        print(f"  Progress: {idx}/{len(slot_order)} slots filled ({elapsed:.1f}s) - last: {d} len={l}", flush=True)

    slot_idx = slot_order[idx]
    direction, cells, length = slots[slot_idx]
    pattern = [grid[r][c] for r, c in cells]

    candidates = get_candidates(word_dict, length, pattern, used_words)
    random.shuffle(candidates)

    # Prefer words with common letters
    common = "ETAOINSHRDLCUMWFGYPBVKJXQZ"
    candidates.sort(key=lambda item: sum(common.index(c) if c in common else 26 for c in item[0]))

    for word, clue in candidates:
        old_grid = [row[:] for row in grid]
        for i, (r, c) in enumerate(cells):
            grid[r][c] = word[i]
        used_words.add(word)

        # Forward check: verify crossing slots still have candidates
        viable = True
        for j in range(idx + 1, min(idx + 20, len(slot_order))):
            oi = slot_order[j]
            _, oc, ol = slots[oi]
            op = [grid[r][c] for r, c in oc]
            if any(p != '.' for p in op):
                if count_candidates(word_dict, ol, op, used_words) == 0:
                    viable = False
                    break

        if viable and solve(grid, slots, word_dict, slot_order, idx + 1,
                           used_words, start_time, time_limit, best_progress):
            return True

        used_words.discard(word)
        for r in range(len(grid)):
            for c in range(len(grid[0])):
                grid[r][c] = old_grid[r][c]

    return False


def assign_clue_numbers(grid):
    """Assign clue numbers following crossword conventions."""
    rows, cols = len(grid), len(grid[0])
    numbers = {}
    num = 1
    for r in range(rows):
        for c in range(cols):
            if grid[r][c] == '#':
                continue
            starts_across = (c == 0 or grid[r][c-1] == '#') and (c + 1 < cols and grid[r][c+1] != '#')
            starts_down = (r == 0 or grid[r-1][c] == '#') and (r + 1 < rows and grid[r+1][c] != '#')
            if starts_across or starts_down:
                numbers[(r, c)] = num
                num += 1
    return numbers


def generate_puzzle():
    """Main puzzle generation function."""
    print("Building word dictionary...", flush=True)
    word_dict = {}
    for length, words in WORDS.items():
        word_dict[length] = [(w.upper(), c) for w, c in words]
        print(f"  {length}-letter words: {len(word_dict[length])}", flush=True)

    # Verify template symmetry
    errors = verify_template(TEMPLATE)
    if errors:
        print(f"Template symmetry errors: {errors}")
        return None
    print("Template symmetry verified ✓", flush=True)

    grid = [row[:] for row in TEMPLATE]
    slots = get_template_slots(grid)
    print(f"\nFound {len(slots)} slots", flush=True)

    # Verify no slots with insufficient word options
    for d, cells, l in slots:
        if l not in word_dict or len(word_dict[l]) == 0:
            print(f"WARNING: No words of length {l}!")
            return None
        print(f"  {d}: len={l} at ({cells[0][0]},{cells[0][1]}) - {len(word_dict[l])} candidates", flush=True)

    # Build intersection map
    cell_to_slots = {}
    for i, (_, cells, _) in enumerate(slots):
        for cell in cells:
            cell_to_slots.setdefault(cell, []).append(i)

    intersection_count = {}
    for i, (_, cells, _) in enumerate(slots):
        intersection_count[i] = sum(1 for cell in cells if len(cell_to_slots[cell]) > 1)

    # Order: shortest first, then most intersections
    slot_order = sorted(range(len(slots)), key=lambda i: (slots[i][2], -intersection_count[i]))

    print(f"\nSolving {len(slots)} slots...", flush=True)
    start_time = time.time()
    used_words = set()
    best_progress = [0]

    success = solve(grid, slots, word_dict, slot_order, 0, used_words,
                   start_time, time_limit=300, best_progress=best_progress)

    elapsed = time.time() - start_time
    print(f"\nSolve {'SUCCEEDED' if success else 'FAILED'} in {elapsed:.1f}s", flush=True)

    if not success:
        return None

    # Print grid
    print("\nFilled grid:", flush=True)
    for row in grid:
        print(' '.join(row))

    # Build puzzle JSON
    numbers = assign_clue_numbers(grid)
    word_clue_map = {}
    for length, words in word_dict.items():
        for word, clue in words:
            word_clue_map[word] = clue

    across_clues, down_clues = [], []
    for direction, cells, length in slots:
        word = ''.join(grid[r][c] for r, c in cells)
        start_r, start_c = cells[0]
        num = numbers.get((start_r, start_c))
        if num is None:
            continue
        clue_obj = {
            "number": num,
            "clue": word_clue_map.get(word, f"[{word}]"),
            "answer": word,
            "row": start_r,
            "col": start_c
        }
        (across_clues if direction == 'across' else down_clues).append(clue_obj)

    across_clues.sort(key=lambda x: x["number"])
    down_clues.sort(key=lambda x: x["number"])

    # Validate
    errors = 0
    for clue_list, dir_name in [(across_clues, "across"), (down_clues, "down")]:
        for clue in clue_list:
            word = clue["answer"]
            r, c = clue["row"], clue["col"]
            for i, ch in enumerate(word):
                gr, gc = (r, c + i) if dir_name == "across" else (r + i, c)
                if grid[gr][gc] != ch:
                    print(f"ERROR: {dir_name} {clue['number']} '{word}' mismatch at pos {i}")
                    errors += 1

    print(f"\nAcross: {len(across_clues)}, Down: {len(down_clues)}, Total: {len(across_clues)+len(down_clues)}")
    if errors:
        print(f"{errors} validation errors!")
    else:
        print("All clues validated ✓")

    return {
        "id": "puzzle_001",
        "version": 1,
        "size": {"rows": 15, "cols": 15},
        "difficulty": "medium",
        "theme": "General Knowledge",
        "date": None,
        "grid": [list(row) for row in grid],
        "clues": {"across": across_clues, "down": down_clues},
        "tags": ["general", "15x15"],
        "author": "CouchWord"
    }


